"""
MODULE 6: TRADING SIGNALS & RISK ANALYSIS
==========================================
Generates ML-based trading signals (BUY / HOLD / SELL) and assesses investment risk.

Formulas & Logic:
1. Expected Return (%):
   Expected Return = ((Predicted Next Close - Current Close) / Current Close) * 100

2. Signal Generation (Configurable Threshold, default ±1.5% - 2.0%):
   - Expected Return > +threshold%  -> BUY  (Bullish momentum expected)
   - Expected Return < -threshold%  -> SELL (Bearish pullback expected)
   - Otherwise                      -> HOLD (Neutral / Consolidation)

3. Risk Level Classification (Annualized 20-day historical volatility):
   - Volatility < 20%              -> LOW RISK    (Stable large-cap behavior)
   - 20% <= Volatility <= 35%      -> MEDIUM RISK (Moderate price swings)
   - Volatility > 35%              -> HIGH RISK   (High fluctuation / speculative)

DISCLAIMER:
All generated signals are purely educational heuristics and do NOT constitute financial advice.
"""

import numpy as np


DISCLAIMER_TEXT = (
    "DISCLAIMER: This prediction and trading signal is generated by an educational "
    "Machine Learning model for academic demonstration. Financial markets are subject "
    "to systemic risk and high unpredictability. This output is NOT financial advice. "
    "Never execute real trades solely based on automated statistical forecasts."
)


def calculate_expected_return(current_price: float, predicted_price: float) -> float:
    """
    Compute percentage expected return between today's close and tomorrow's prediction.
    """
    if current_price <= 0:
        return 0.0
    return ((predicted_price - current_price) / current_price) * 100.0


def generate_trading_signal(
    current_price: float,
    predicted_price: float,
    buy_threshold: float = 1.5,
    sell_threshold: float = -1.5
) -> tuple[str, float, str]:
    """
    Generate an indicative BUY / HOLD / SELL trading signal.

    Parameters
    ----------
    current_price   : Today's closing price
    predicted_price : Tomorrow's model-predicted closing price
    buy_threshold   : Expected return % above which signal is BUY
    sell_threshold  : Expected return % below which signal is SELL

    Returns
    -------
    (signal, expected_return_pct, explanation)
    """
    expected_return = calculate_expected_return(current_price, predicted_price)

    if expected_return >= buy_threshold:
        signal = "BUY"
        explanation = (
            f"The model forecasts an upward movement of +{expected_return:.2f}%, "
            f"exceeding the +{buy_threshold:.1f}% threshold, suggesting potential bullish momentum."
        )
    elif expected_return <= sell_threshold:
        signal = "SELL"
        explanation = (
            f"The model forecasts a downward movement of {expected_return:.2f}%, "
            f"falling below the {sell_threshold:.1f}% threshold, suggesting potential bearish pullback."
        )
    else:
        signal = "HOLD"
        explanation = (
            f"The projected movement of {expected_return:+.2f}% is within the neutral band "
            f"({sell_threshold:.1f}% to +{buy_threshold:.1f}%), suggesting market consolidation."
        )

    return signal, round(expected_return, 2), explanation


def classify_risk(annualized_volatility: float) -> tuple[str, str, str]:
    """
    Classify risk level based on 20-day annualized historical volatility.

    Parameters
    ----------
    annualized_volatility : Annualized standard deviation of daily returns (e.g., 0.22 = 22%)

    Returns
    -------
    (risk_level, color_code, rationale)
    """
    vol_pct = annualized_volatility * 100.0

    if vol_pct < 20.0:
        level = "LOW RISK"
        color = "#10B981"  # Emerald green
        rationale = (
            f"Annualized volatility is {vol_pct:.1f}% (< 20%). "
            "Price exhibits steady, low-fluctuation behavior typical of defensive assets."
        )
    elif vol_pct <= 35.0:
        level = "MEDIUM RISK"
        color = "#F59E0B"  # Amber
        rationale = (
            f"Annualized volatility is {vol_pct:.1f}% (between 20% and 35%). "
            "Stock displays standard market volatility with moderate intraday swings."
        )
    else:
        level = "HIGH RISK"
        color = "#EF4444"  # Coral red
        rationale = (
            f"Annualized volatility is {vol_pct:.1f}% (> 35%). "
            "Stock exhibits high variance and sharp price oscillations. Heightened caution advised."
        )

    return level, color, rationale


def build_signal_summary(
    current_price: float,
    predicted_price: float,
    annualized_volatility: float,
    buy_threshold: float = 1.5,
    sell_threshold: float = -1.5
) -> dict:
    """
    Produce a complete signal and risk analysis dictionary ready for dashboard display.
    """
    signal, exp_return, sig_expl = generate_trading_signal(
        current_price, predicted_price, buy_threshold, sell_threshold
    )
    risk_level, risk_color, risk_expl = classify_risk(annualized_volatility)

    signal_colors = {
        "BUY": "#10B981",    # Emerald
        "SELL": "#EF4444",   # Coral Red
        "HOLD": "#F59E0B"    # Amber
    }

    return {
        "current_price": round(current_price, 2),
        "predicted_price": round(predicted_price, 2),
        "expected_return": exp_return,
        "signal": signal,
        "signal_color": signal_colors.get(signal, "#6B7280"),
        "signal_explanation": sig_expl,
        "risk_level": risk_level,
        "risk_color": risk_color,
        "risk_explanation": risk_expl,
        "disclaimer": DISCLAIMER_TEXT
    }
